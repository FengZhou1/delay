function audit = analyze_corrected_unslotted_results( ...
        base_result_dir,corrected_result_dir,matched_sbcb_result_dir)
%ANALYZE_CORRECTED_UNSLOTTED_RESULTS Audit the corrected async RTS model.
%
% Positive values in sb_minus_unslotted_us mean that corrected Unslotted
% has the lower delay. Confidence intervals pair the five formal runs that
% share exactly the same physical arrival trace.

    if nargin < 1 || isempty(base_result_dir)
        study_dir = fileparts(mfilename('fullpath'));
        base_result_dir = fullfile(study_dir,'results','20260729_182732');
    end
    if nargin < 2 || isempty(corrected_result_dir)
        corrected_result_dir = latest_directory_local( ...
            base_result_dir,'corrected_unslotted_*');
    end
    if nargin < 3 || isempty(matched_sbcb_result_dir)
        matched_sbcb_result_dir = latest_directory_local( ...
            base_result_dir,'matched_sbcb_*');
    end

    output_dir = fullfile(corrected_result_dir,'merged_corrected');
    if ~exist(output_dir,'dir')
        error('analyze_corrected_unslotted_results:MissingMerge', ...
            'Run merge_corrected_unslotted_results before this audit.');
    end
    verification_dir = fullfile(output_dir,'verification');
    if ~exist(verification_dir,'dir'), mkdir(verification_dir); end

    condition = readtable(fullfile(corrected_result_dir, ...
        'condition_summary.csv'),'TextType','string');
    runs = readtable(fullfile(corrected_result_dir, ...
        'run_summary.csv'),'TextType','string');
    packets = readtable(fullfile(corrected_result_dir, ...
        'packet_delays.csv'),'TextType','string');
    q_scan = readtable(fullfile(corrected_result_dir, ...
        'q_scan.csv'),'TextType','string');
    q_validation = readtable(fullfile(corrected_result_dir, ...
        'q_validation.csv'),'TextType','string');
    sb_condition = readtable(fullfile(matched_sbcb_result_dir, ...
        'sb_cb_condition_summary.csv'),'TextType','string');
    sb_runs = readtable(fullfile(matched_sbcb_result_dir, ...
        'sb_cb_run_summary.csv'),'TextType','string');
    sb_packets = readtable(fullfile(matched_sbcb_result_dir, ...
        'sb_cb_packet_delays.csv'),'TextType','string');

    assert(height(condition)==18 && all(condition.variant=="unslotted"), ...
        'The corrected study must contain 18 Unslotted conditions.');
    assert(height(runs)==90 && height(sb_runs)==90, ...
        'Expected five formal runs for each of 18 conditions.');

    paired_rows = repmat(empty_paired_row_local(),height(condition),1);
    for index = 1:height(condition)
        lambda = condition.lambda_per_node(index);
        M = condition.M(index);
        corrected = sortrows(runs( ...
            runs.lambda_per_node==lambda & runs.M==M,:),'run');
        sb = sortrows(sb_runs( ...
            sb_runs.lambda_per_node==lambda & sb_runs.M==M,:),'run');
        if height(corrected)~=height(sb) || any(corrected.run~=sb.run)
            error('analyze_corrected_unslotted_results:RunMismatch', ...
                'Run pairing failed for lambda=%g, M=%g.',lambda,M);
        end
        difference = sb.mean_total_delay_us-corrected.mean_total_delay_us;
        [mean_difference,ci95] = mean_ci95_local(difference);
        if mean_difference-ci95 > 0
            interpretation = "Unslotted lower";
        elseif mean_difference+ci95 < 0
            interpretation = "SB-CB lower";
        else
            interpretation = "not resolved";
        end
        sb_row = sb_condition( ...
            sb_condition.lambda_per_node==lambda & sb_condition.M==M,:);
        paired_rows(index) = struct( ...
            'lambda_per_node',lambda,'M',M, ...
            'unslotted_best_q',condition.best_q(index), ...
            'sb_cb_best_q',sb_row.best_q, ...
            'unslotted_mean_total_delay_us', ...
                condition.mean_total_delay_us(index), ...
            'sb_cb_mean_total_delay_us',sb_row.mean_total_delay_us, ...
            'sb_minus_unslotted_us',mean_difference, ...
            'paired_ci95_halfwidth_us',ci95, ...
            'paired_ci95_low_us',mean_difference-ci95, ...
            'paired_ci95_high_us',mean_difference+ci95, ...
            'paired_interpretation',interpretation, ...
            'n_paired_runs',height(corrected));
    end
    paired_comparison = struct2table(paired_rows);

    groups = unique(q_scan(:,{'lambda_per_node','M'}),'rows');
    q_rows = repmat(empty_q_row_local(),height(groups),1);
    for index = 1:height(groups)
        lambda = groups.lambda_per_node(index);
        M = groups.M(index);
        rows = sortrows(q_scan( ...
            q_scan.lambda_per_node==lambda & q_scan.M==M,:),'q');
        stable = rows.q<1-1e-12 & ...
            rows.completion_ratio_mean>=0.99 & ...
            rows.min_completion_ratio>=0.99 & ...
            isfinite(rows.mean_total_delay_us);
        eligible_rows = rows(stable,:);
        [~,raw_index] = min(eligible_rows.mean_total_delay_us);
        raw = eligible_rows(raw_index,:);
        selected_index = find(rows.selected==1,1);
        selected = rows(selected_index,:);
        neighbor_index = max(1,selected_index-1): ...
            min(height(rows),selected_index+1);
        q_min = min(rows.q);
        q_rows(index) = struct( ...
            'lambda_per_node',lambda,'M',M,'n_q',height(rows), ...
            'q_min',q_min,'q_max',max(rows.q), ...
            'raw_min_q',raw.q, ...
            'raw_min_tune_delay_us',raw.mean_total_delay_us, ...
            'selected_q',selected.q, ...
            'selected_tune_delay_us',selected.mean_total_delay_us, ...
            'conservative_penalty_us',selected.mean_total_delay_us- ...
                raw.mean_total_delay_us, ...
            'selected_neighbors_stable',all(stable(neighbor_index)), ...
            'selected_at_lower_boundary',abs(selected.q-q_min)<1e-12, ...
            'raw_min_at_lower_boundary',abs(raw.q-q_min)<1e-12);
    end
    q_selection_audit = struct2table(q_rows);

    packet_keys = {'lambda_per_node','M','run','packet_id'};
    packets = sortrows(packets,packet_keys);
    sb_packets = sortrows(sb_packets,packet_keys);
    arrival_traces_match = height(packets)==height(sb_packets) && ...
        isequal(packets.lambda_per_node,sb_packets.lambda_per_node) && ...
        isequal(packets.M,sb_packets.M) && ...
        isequal(packets.run,sb_packets.run) && ...
        isequal(packets.packet_id,sb_packets.packet_id) && ...
        isequal(packets.node_id,sb_packets.node_id) && ...
        isequal(packets.arrival_us,sb_packets.arrival_us);

    checks = struct();
    checks.n_conditions = height(condition);
    checks.n_runs = height(runs);
    checks.n_packets = height(packets);
    checks.all_completion_one = all(runs.completion_ratio==1);
    checks.all_stable = all(runs.stable==1);
    checks.all_packet_conservation = all(runs.packet_conservation_ok==1);
    checks.all_final_backlog_zero = all(runs.final_backlog==0);
    checks.all_packets_completed = all(packets.completed==1);
    checks.all_arrival_traces_match_matched_sb_cb = arrival_traces_match;
    checks.all_selected_q_validated = ...
        height(q_validation)==height(condition) && ...
        all(q_validation.passed==1);
    checks.all_selected_q_neighbors_stable = ...
        all(q_selection_audit.selected_neighbors_stable);
    checks.no_raw_q_minimum_at_scan_lower_boundary = ...
        ~any(q_selection_audit.raw_min_at_lower_boundary);
    checks.n_paired_points_unslotted_lower_mean = ...
        sum(paired_comparison.sb_minus_unslotted_us>0);
    checks.n_paired_points_ci_resolves_unslotted_lower = ...
        sum(paired_comparison.paired_interpretation=="Unslotted lower");
    checks.n_paired_points_ci_resolves_sb_cb_lower = ...
        sum(paired_comparison.paired_interpretation=="SB-CB lower");
    checks.max_delay_identity_error_us = ...
        max(condition.delay_identity_error_us);
    checks.verification_status = "VERIFIED";

    writetable(paired_comparison,fullfile(output_dir, ...
        'corrected_unslotted_vs_sb_cb_paired.csv'));
    writetable(q_selection_audit,fullfile(output_dir, ...
        'corrected_unslotted_q_selection_audit.csv'));
    write_json_local(fullfile(verification_dir, ...
        'posthoc_verification.json'),checks);

    manifest_path = fullfile(output_dir,'manifest.json');
    manifest = jsondecode(fileread(manifest_path));
    manifest.verification_status = 'VERIFIED';
    manifest.posthoc_verification = fullfile(verification_dir, ...
        'posthoc_verification.json');
    manifest.paired_comparison = fullfile(output_dir, ...
        'corrected_unslotted_vs_sb_cb_paired.csv');
    manifest.q_selection_audit = fullfile(output_dir, ...
        'corrected_unslotted_q_selection_audit.csv');
    write_json_local(manifest_path,manifest);

    audit = struct('paired_comparison',paired_comparison, ...
        'q_selection',q_selection_audit,'checks',checks, ...
        'output_dir',string(output_dir));
end

function [sample_mean,ci95] = mean_ci95_local(values)
    values = double(values(:));
    sample_mean = mean(values);
    n = numel(values);
    if n < 2
        ci95 = NaN;
        return;
    end
    x = betaincinv(0.05,(n-1)/2,0.5);
    t_critical = sqrt((n-1)*(1/x-1));
    ci95 = t_critical*std(values)/sqrt(n);
end

function row = empty_paired_row_local()
    row = struct('lambda_per_node',0,'M',0, ...
        'unslotted_best_q',0,'sb_cb_best_q',0, ...
        'unslotted_mean_total_delay_us',0, ...
        'sb_cb_mean_total_delay_us',0, ...
        'sb_minus_unslotted_us',0, ...
        'paired_ci95_halfwidth_us',0, ...
        'paired_ci95_low_us',0,'paired_ci95_high_us',0, ...
        'paired_interpretation',"",'n_paired_runs',0);
end

function row = empty_q_row_local()
    row = struct('lambda_per_node',0,'M',0,'n_q',0, ...
        'q_min',0,'q_max',0,'raw_min_q',0, ...
        'raw_min_tune_delay_us',0,'selected_q',0, ...
        'selected_tune_delay_us',0,'conservative_penalty_us',0, ...
        'selected_neighbors_stable',false, ...
        'selected_at_lower_boundary',false, ...
        'raw_min_at_lower_boundary',false);
end

function path = latest_directory_local(parent,pattern)
    candidates = dir(fullfile(parent,pattern));
    candidates = candidates([candidates.isdir]);
    if isempty(candidates)
        error('analyze_corrected_unslotted_results:MissingDirectory', ...
            'No directory matching %s exists under %s.',pattern,parent);
    end
    [~,latest] = max([candidates.datenum]); %#ok<DATNM>
    path = fullfile(candidates(latest).folder,candidates(latest).name);
end

function write_json_local(path,value)
    fid = fopen(path,'w');
    if fid<0
        error('analyze_corrected_unslotted_results:JsonOpenFailed', ...
            'Cannot open %s.',path);
    end
    cleanup = onCleanup(@() fclose(fid));
    fwrite(fid,jsonencode(value,'PrettyPrint',true),'char');
end
