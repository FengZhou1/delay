function merged = merge_corrected_unslotted_results( ...
        base_result_dir,corrected_result_dir,matched_sbcb_result_dir)
%MERGE_CORRECTED_UNSLOTTED_RESULTS Replace only obsolete Unslotted rows.

    sf_condition = readtable(fullfile(base_result_dir, ...
        'condition_summary.csv'),'TextType','string');
    sf_run = readtable(fullfile(base_result_dir, ...
        'run_summary.csv'),'TextType','string');
    sf_q_scan = readtable(fullfile(base_result_dir, ...
        'q_scan.csv'),'TextType','string');
    sf_q_validation = readtable(fullfile(base_result_dir, ...
        'q_validation.csv'),'TextType','string');
    sf_packet = readtable(fullfile(base_result_dir, ...
        'packet_delays.csv'),'TextType','string');

    corrected_condition = readtable(fullfile(corrected_result_dir, ...
        'condition_summary.csv'),'TextType','string');
    corrected_run = readtable(fullfile(corrected_result_dir, ...
        'run_summary.csv'),'TextType','string');
    corrected_q_scan = readtable(fullfile(corrected_result_dir, ...
        'q_scan.csv'),'TextType','string');
    corrected_q_validation = readtable(fullfile(corrected_result_dir, ...
        'q_validation.csv'),'TextType','string');
    corrected_packet = readtable(fullfile(corrected_result_dir, ...
        'packet_delays.csv'),'TextType','string');

    assert(all(corrected_condition.variant=="unslotted"), ...
        'Corrected result must contain only Unslotted rows.');
    assert(height(corrected_condition)==18, ...
        'Corrected result must contain 18 conditions.');

    keep_condition = sf_condition.variant~="unslotted";
    keep_run = sf_run.variant~="unslotted";
    keep_q_scan = sf_q_scan.variant~="unslotted";
    keep_q_validation = sf_q_validation.variant~="unslotted";
    keep_packet = sf_packet.variant~="unslotted";

    condition_table = [sf_condition(keep_condition,:);corrected_condition];
    run_table = [sf_run(keep_run,:);corrected_run];
    q_scan_table = [sf_q_scan(keep_q_scan,:);corrected_q_scan];
    q_validation_table = [sf_q_validation(keep_q_validation,:); ...
        corrected_q_validation];
    packet_delay_table = [sf_packet(keep_packet,:);corrected_packet];

    condition_table = sortrows(condition_table, ...
        {'lambda_per_node','M','variant'});
    run_table = sortrows(run_table, ...
        {'lambda_per_node','M','variant','run'});
    q_scan_table = sortrows(q_scan_table, ...
        {'lambda_per_node','M','variant','q'});
    q_validation_table = sortrows(q_validation_table, ...
        {'lambda_per_node','M','variant','candidate_rank'});
    packet_delay_table = sortrows(packet_delay_table, ...
        {'lambda_per_node','M','variant','run','packet_id'});

    merged_dir = fullfile(corrected_result_dir,'merged_corrected');
    if ~exist(merged_dir,'dir'), mkdir(merged_dir); end
    writetable(condition_table,fullfile(merged_dir, ...
        'condition_summary_corrected.csv'));
    writetable(run_table,fullfile(merged_dir, ...
        'run_summary_corrected.csv'));
    writetable(q_scan_table,fullfile(merged_dir, ...
        'q_scan_corrected.csv'));
    writetable(q_validation_table,fullfile(merged_dir, ...
        'q_validation_corrected.csv'));
    writetable(packet_delay_table,fullfile(merged_dir, ...
        'packet_delays_corrected.csv'));

    sf_figure = plot_sfcb_lightload_results(condition_table,merged_dir);

    sb_condition = readtable(fullfile(matched_sbcb_result_dir, ...
        'sb_cb_condition_summary.csv'),'TextType','string');
    combined_condition_table = [condition_table;sb_condition];
    combined_condition_table = sortrows(combined_condition_table, ...
        {'lambda_per_node','M','variant'});
    writetable(combined_condition_table,fullfile(merged_dir, ...
        'condition_summary_corrected_with_sb_cb.csv'));
    combined_figure = plot_sfcb_sbcb_matched_results( ...
        combined_condition_table,merged_dir);

    save(fullfile(merged_dir,'merged_corrected_results.mat'), ...
        'condition_table','run_table','q_scan_table', ...
        'q_validation_table','packet_delay_table', ...
        'combined_condition_table','-v7.3');

    manifest = struct('schema_version','1.0', ...
        'study_type','corrected_unslotted_merge', ...
        'status','completed','verification_status','UNVERIFIED', ...
        'created_at',char(datetime('now', ...
            'Format','yyyy-MM-dd HH:mm:ss')), ...
        'base_result_dir',base_result_dir, ...
        'corrected_result_dir',corrected_result_dir, ...
        'matched_sbcb_result_dir',matched_sbcb_result_dir, ...
        'n_sf_conditions',height(condition_table), ...
        'n_combined_conditions',height(combined_condition_table), ...
        'sf_figure_png',sf_figure.png_path, ...
        'combined_figure_png',combined_figure.png_path);
    write_json_local(fullfile(merged_dir,'manifest.json'),manifest);

    merged = struct('output_dir',merged_dir, ...
        'condition_summary',condition_table, ...
        'run_summary',run_table,'q_scan',q_scan_table, ...
        'q_validation',q_validation_table, ...
        'packet_delays',packet_delay_table, ...
        'combined_condition_summary',combined_condition_table, ...
        'sf_figure',sf_figure,'combined_figure',combined_figure, ...
        'manifest',manifest);
end

function write_json_local(path,value)
    fid = fopen(path,'w');
    if fid<0
        error('merge_corrected_unslotted_results:JsonOpenFailed', ...
            'Cannot open %s.',path);
    end
    cleanup = onCleanup(@() fclose(fid));
    fwrite(fid,jsonencode(value,'PrettyPrint',true),'char');
end
